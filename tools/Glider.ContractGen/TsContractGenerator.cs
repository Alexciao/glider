using System.Collections;
using System.Reflection;
using System.Text;
using System.Text.Json;
using Glider.Core.Contracts;

namespace Glider.ContractGen;

/// <summary>
/// Generates TypeScript declarations for the IPC contract by reflecting over <see cref="IGliderRpc"/>,
/// its [RpcEvent]s and every type reachable from them. Output is deterministic (sorted).
/// </summary>
public static class TsContractGenerator
{
    public const string RelativeOutputPath = "frontend/src/ipc/contract.gen.ts";

    private static readonly NullabilityInfoContext Nullability = new();

    public static string Generate()
    {
        var types = new SortedDictionary<string, Type>(StringComparer.Ordinal);
        var methods = new List<(string Name, string Params, string Result, string? Doc)>();

        foreach (var m in typeof(IGliderRpc).GetMethods().OrderBy(m => m.GetCustomAttribute<RpcMethodAttribute>()!.Name, StringComparer.Ordinal))
        {
            var name = m.GetCustomAttribute<RpcMethodAttribute>()!.Name;
            var ps = m.GetParameters();
            var param = ps.Length == 0 ? "void" : TsType(ps[0].ParameterType, Nullability.Create(ps[0]), types);
            var result = "void";
            if (m.ReturnType.IsGenericType)
            {
                var info = Nullability.Create(m.ReturnParameter);
                result = TsType(m.ReturnType.GetGenericArguments()[0], info.GenericTypeArguments[0], types);
            }

            methods.Add((name, param, result, null));
        }

        var events = typeof(IGliderRpc).GetCustomAttributes<RpcEventAttribute>()
            .OrderBy(e => e.Name, StringComparer.Ordinal)
            .Select(e => (e.Name, Type: TsType(e.Payload, null, types)))
            .ToList();

        // Envelopes are part of the wire contract too.
        TsType(typeof(RpcRequest), null, types);
        TsType(typeof(RpcResponse), null, types);
        TsType(typeof(RpcEvent), null, types);

        var sb = new StringBuilder();
        sb.Append("// AUTO-GENERATED by tools/Glider.ContractGen from src/Glider.Core/Contracts. DO NOT EDIT.\n");
        sb.Append("// Regenerate: dotnet run --project tools/Glider.ContractGen\n");
        sb.Append("/* eslint-disable */\n\n");

        // Emit types: drain the queue since emitting may discover more types.
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var bodies = new SortedDictionary<string, string>(StringComparer.Ordinal);
        while (true)
        {
            var pending = types.Where(kv => !emitted.Contains(kv.Key)).ToList();
            if (pending.Count == 0)
            {
                break;
            }

            foreach (var (name, type) in pending)
            {
                emitted.Add(name);
                bodies[name] = EmitType(type, types);
            }
        }

        foreach (var body in bodies.Values)
        {
            sb.Append(body).Append('\n');
        }

        sb.Append("/** Request/response map: method name → params and result types. */\n");
        sb.Append("export interface RpcMethods {\n");
        foreach (var (name, p, r, _) in methods)
        {
            sb.Append("  \"").Append(name).Append("\": { params: ").Append(p).Append("; result: ").Append(r).Append(" };\n");
        }

        sb.Append("}\n\n");
        sb.Append("export type RpcMethodName = keyof RpcMethods;\n\n");
        sb.Append("/** Server-pushed events: event name → payload type. */\n");
        sb.Append("export interface RpcEventMap {\n");
        foreach (var (name, type) in events)
        {
            sb.Append("  \"").Append(name).Append("\": ").Append(type).Append(";\n");
        }

        sb.Append("}\n\n");
        sb.Append("export type RpcEventName = keyof RpcEventMap;\n\n");
        sb.Append("export const RPC_METHODS = [\n");
        foreach (var (name, _, _, _) in methods)
        {
            sb.Append("  \"").Append(name).Append("\",\n");
        }

        sb.Append("] as const satisfies readonly RpcMethodName[];\n");
        return sb.ToString();
    }

    private static string EmitType(Type type, SortedDictionary<string, Type> types)
    {
        var sb = new StringBuilder();
        if (type.IsEnum)
        {
            var values = Enum.GetNames(type).Select(n => $"\"{JsonNamingPolicy.CamelCase.ConvertName(n)}\"");
            sb.Append("export type ").Append(type.Name).Append(" = ").Append(string.Join(" | ", values)).Append(";\n");
            return sb.ToString();
        }

        sb.Append("export interface ").Append(type.Name).Append(" {\n");
        foreach (var p in type.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.GetMethod is not null && !p.GetMethod.IsStatic))
        {
            if (p.Name == "EqualityContract")
            {
                continue;
            }

            var info = Nullability.Create(p);
            sb.Append("  ").Append(JsonNamingPolicy.CamelCase.ConvertName(p.Name)).Append(": ")
              .Append(TsType(p.PropertyType, info, types)).Append(";\n");
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    private static string TsType(Type t, NullabilityInfo? info, SortedDictionary<string, Type> types)
    {
        var underlying = Nullable.GetUnderlyingType(t);
        var nullable = underlying is not null || info?.ReadState == NullabilityState.Nullable;
        var core = TsCore(underlying ?? t, info, types);
        return nullable ? $"{core} | null" : core;
    }

    private static string TsCore(Type t, NullabilityInfo? info, SortedDictionary<string, Type> types)
    {
        if (t == typeof(string) || t == typeof(DateTimeOffset) || t == typeof(DateTime) || t == typeof(Guid))
        {
            return "string";
        }

        if (t == typeof(bool))
        {
            return "boolean";
        }

        if (t == typeof(int) || t == typeof(long) || t == typeof(double) || t == typeof(float) || t == typeof(decimal) || t == typeof(short) || t == typeof(byte) || t == typeof(uint) || t == typeof(ulong))
        {
            return "number";
        }

        if (t == typeof(JsonElement) || t == typeof(object))
        {
            return "unknown";
        }

        if (t.IsArray)
        {
            return $"{Wrap(TsType(t.GetElementType()!, info?.ElementType, types))}[]";
        }

        if (t.IsGenericType)
        {
            var def = t.GetGenericTypeDefinition();
            var args = t.GetGenericArguments();
            if (def == typeof(Dictionary<,>) || def == typeof(IReadOnlyDictionary<,>) || def == typeof(IDictionary<,>))
            {
                return $"Record<string, {TsType(args[1], info?.GenericTypeArguments.ElementAtOrDefault(1), types)}>";
            }

            if (typeof(IEnumerable).IsAssignableFrom(t))
            {
                return $"{Wrap(TsType(args[0], info?.GenericTypeArguments.ElementAtOrDefault(0), types))}[]";
            }
        }

        if (t.IsEnum || (t.IsClass && t.Namespace == typeof(IGliderRpc).Namespace))
        {
            types.TryAdd(t.Name, t);
            return t.Name;
        }

        throw new NotSupportedException($"No TS mapping for {t}");
    }

    private static string Wrap(string ts) => ts.Contains('|', StringComparison.Ordinal) ? $"({ts})" : ts;
}
